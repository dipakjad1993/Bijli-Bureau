function text(str, x0, y0, sc, col) {
  let x = x0;
  for (const ch of str.toUpperCase()) {
    const g = F[ch] || F[" "];
    for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++)
      if (g[r][c] === "1") for (let dy = 0; dy < sc; dy++) for (let dx = 0; dx < sc; dx++)
        set(x + c * sc + dx, y0 + r * sc + dy, col[0], col[1], col[2]);
    x += (5 * sc + 2 * sc);
  }
  return x;
}
